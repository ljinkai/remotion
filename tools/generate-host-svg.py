"""Compile the verified SVG master into synchronous React layer data.

Run python3 tools/generate-host-svg.py after rebuilding the experiment master.
Only standard-library modules are required; no browser fetch is used at runtime.
"""
from pathlib import Path
import json
import shutil
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MASTER = ROOT / "experiments/svg-host-poc/character.svg"
ET.register_namespace("", "http://www.w3.org/2000/svg")
root = ET.parse(MASTER).getroot()
groups = {node.attrib.get("id"): node for node in root if node.tag.endswith("g")}

def children(node):
    return "".join(ET.tostring(child, encoding="unicode") for child in node)

mouth = groups["mouth"]
data = {
    "viewBox": root.attrib["viewBox"],
    "body": children(groups["body"]),
    "arm": children(groups["pointing-arm"]),
    "eyelids": children(groups["eyelids"]),
    "mouthTransform": mouth.attrib["transform"],
    "mouths": {node.attrib["id"].removeprefix("mouth-"): children(node) for node in mouth},
}
target = ROOT / "src/host-explainer/host/character.generated.ts"
target.write_text(
    "// Generated by tools/generate-host-svg.py from the verified vector master.\n"
    "// Do not edit path data here. No raster images or runtime requests.\n"
    + "export const hostCharacter = " + json.dumps(data, ensure_ascii=False, indent=2)
    + " as const;\n"
)
shutil.copyfile(MASTER, ROOT / "public/charactar/character.svg")
print(f"Generated {target.relative_to(ROOT)} and public/charactar/character.svg")
